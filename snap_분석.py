# 리트윗 네트워크 도식화: 인기 상위 허브 주변 샘플
# (25만 노드 전체는 그려도 점 덩어리라, 허브 주변만 뽑아서 구조를 보여줌)
# =====================================================================
import gzip, random
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

NAVY, AMBER, TEAL, GRAY = "#1B1F3B", "#E8A33D", "#2A9D8F", "#B8BCCF"
TOP_HUBS, PER_HUB, SEED = 5, 120, 42   # 허브 5개 × 허브당 리트윗한 사용자 최대 120명
random.seed(SEED)

if "G_hig" not in globals():
    G_hig = nx.DiGraph()
    with gzip.open("higgs-retweet_network.edgelist.gz", "rt") as f:
        for line in f:
            u, v, _ = line.split()
            G_hig.add_edge(int(u), int(v))

# 1) 샘플 추출: In-degree 상위 허브 + 각 허브를 리트윗한 사용자 일부
hubs = [n for n, _ in sorted(G_hig.in_degree(), key=lambda x: -x[1])[:TOP_HUBS]]
nodes = set(hubs)
for h in hubs:
    preds = list(G_hig.predecessors(h))
    nodes.update(random.sample(preds, min(PER_HUB, len(preds))))
H = G_hig.subgraph(nodes).copy()

# 2) 노드 역할 (전체 그래프 기준)
def role(n):
    if n in hubs:
        return "hub"
    if G_hig.in_degree(n) > 0 and G_hig.out_degree(n) > 0:
        return "both"      # 리트윗을 받기도, 하기도 함 → 중개 가능
    return "leaf"          # 리트윗만 함
roles = {n: role(n) for n in H}
color = {"hub": AMBER, "both": TEAL, "leaf": GRAY}
size = {n: (900 if roles[n] == "hub" else 60 if roles[n] == "both" else 18) for n in H}

# 3) 그리기
pos = nx.spring_layout(H.to_undirected(), seed=SEED, k=0.08, iterations=200)
fig, ax = plt.subplots(figsize=(9, 7))
nx.draw_networkx_edges(H, pos, ax=ax, edge_color=NAVY, alpha=0.12, width=0.6, arrows=False)
for r in ["leaf", "both", "hub"]:            # 허브가 맨 위에 오도록 순서대로
    ns = [n for n in H if roles[n] == r]
    nx.draw_networkx_nodes(H, pos, nodelist=ns, node_color=color[r],
                           node_size=[size[n] for n in ns], ax=ax, linewidths=0)
for i, h in enumerate(hubs, 1):
    x, y = pos[h]
    ax.text(x, y + 0.07, f"Hub {i}\n{G_hig.in_degree(h):,}", ha="center", va="bottom",
            fontsize=9, color=NAVY, fontweight="bold")
ax.legend(handles=[
    Line2D([], [], marker="o", ls="", color=AMBER, ms=12, label="Top hubs (label = in-degree)"),
    Line2D([], [], marker="o", ls="", color=TEAL, ms=7, label="Retweeted AND retweets (possible broker)"),
    Line2D([], [], marker="o", ls="", color=GRAY, ms=5, label="Only retweets"),
], loc="upper center", bbox_to_anchor=(0.5, 0.0), ncol=3, fontsize=8.5, frameon=False)
ax.set_title(f"Retweet network around the top {TOP_HUBS} hubs (sample)", color=NAVY)
ax.axis("off")
fig.tight_layout(); fig.savefig("fig_network_hubs.png", dpi=200); plt.show()

share_both = np.mean([roles[n] == "both" for n in H if roles[n] != "hub"])
print(f"샘플: 노드 {H.number_of_nodes():,}개, 엣지 {H.number_of_edges():,}개")
print(f"허브를 제외한 사용자 중 '받기도 하고 하기도 함' 비율: {share_both:.1%}")

