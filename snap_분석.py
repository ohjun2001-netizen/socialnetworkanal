HIGGS_K_DIRECTED   = 500   # 셀 1과 동일한 샘플링 조건
HIGGS_K_UNDIRECTED = 200   # 무방향은 출발점당 계산이 무거워 200 (수 분 소요)

def fetch(key):
    if not os.path.exists(FILES[key]):
        print(f"다운로드: {URLS[key]}")
        urllib.request.urlretrieve(URLS[key], FILES[key])
    return FILES[key]

# ---------- 1. 데이터 적재 ----------
def load_higgs():
    G = nx.DiGraph()
    with gzip.open(fetch("higgs"), "rt") as f:
        for line in f:
            u, v, _ = line.split()
            G.add_edge(int(u), int(v))          # u → v : u가 v를 리트윗
    return G

def load_bitcoin():
    df = pd.read_csv(fetch("bitcoin"), header=None,
                     names=["source", "target", "rating", "time"])
    pos = df[df.rating > 0]                     # 신뢰(+) 평가만 사용
    print(f"[Bitcoin OTC] 전체 평가 {len(df):,}건 중 신뢰(+) {len(pos):,}건 ({len(pos)/len(df):.1%}) 사용")
    G = nx.DiGraph()
    G.add_edges_from(zip(pos.source, pos.target))  # source → target : source가 target을 신뢰
    return G

def load_911():
    with zipfile.ZipFile(fetch("911")) as z:
        names = z.namelist()
        edge_f = next(n for n in names if "edge" in n.lower())
        node_f = next((n for n in names if "node" in n.lower()), None)
        edges = pd.read_csv(io.BytesIO(z.read(edge_f)), skipinitialspace=True, index_col=False)
        G = nx.Graph()
        G.add_edges_from(zip(edges.iloc[:, 0].astype(int), edges.iloc[:, 1].astype(int)))
        if node_f:                                # 노드 이름 붙이기 (Atta 등 확인용)
            nodes = pd.read_csv(io.BytesIO(z.read(node_f)), skipinitialspace=True, index_col=False)
            nodes.columns = [c.strip().lstrip("#").strip() for c in nodes.columns]
            name_col = next((c for c in nodes.columns if c.lower() == "name"), None)
            if name_col:
                labels = dict(zip(nodes.iloc[:, 0].astype(int), nodes[name_col].astype(str).str.strip()))
                G = nx.relabel_nodes(G, labels)
    return G

# ---------- 2. 공통 분석 함수 ----------
def analyze(G, name, mode, k=None, seed=42):
    """mode='directed'  : in-degree vs 방향 betweenness
       mode='undirected': degree    vs 무방향 betweenness"""
    H = G if mode == "directed" else (G.to_undirected() if G.is_directed() else G)
    deg = dict(H.in_degree()) if mode == "directed" else dict(H.degree())
    t0 = time.time()
    if k is not None and k < H.number_of_nodes():
        bc = nx.betweenness_centrality(H, k=k, seed=seed)
        how = f"sampled k={k}"
    else:
        bc = nx.betweenness_centrality(H)
        how = "exact"
    secs = time.time() - t0

    d = pd.DataFrame({"degree": pd.Series(deg), "betweenness": pd.Series(bc)})
    d = d[d.degree > 0]                          # 연결(인기)이 1 이상인 노드만
    rho, p = spearmanr(d.degree, d.betweenness)
    tau, _ = kendalltau(d.degree, d.betweenness)

    top_n = 10
    top_deg = set(d.nlargest(top_n, "degree").index)
    top_bc  = set(d[d.betweenness > 0].nlargest(top_n, "betweenness").index)

    row = {
        "Network": name, "Mode": mode, "Betweenness": how,
        "Nodes": H.number_of_nodes(), "Edges": H.number_of_edges(),
        "Reciprocity": round(nx.reciprocity(G), 3) if G.is_directed() else np.nan,
        "Avg clustering": round(nx.average_clustering(H.to_undirected() if H.is_directed() else H), 3),
        "n (degree>0)": len(d),
        "Share bc=0": round((d.betweenness == 0).mean(), 3),
        "Spearman rho": round(rho, 3), "p-value": p,
        "Kendall tau-b": round(tau, 3),
        "Top-10 overlap": f"{len(top_deg & top_bc)}/10",
        "time(s)": round(secs),
    }
    return row, d

