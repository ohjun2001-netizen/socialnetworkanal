import urllib.request
import gzip
import copy
import torch
import networkx as nx
import numpy as np
import matplotlib.pyplot as plt
from torch_geometric.data import Data
import torch_geometric.transforms as T
from torch_geometric.nn import GAE, GCNConv
from torch_geometric.utils import degree, to_undirected
from sklearn.metrics import roc_curve, auc, average_precision_score, f1_score, precision_recall_curve

torch.manual_seed(42)  # [수정] 재현성

# 1. 데이터 수집 및 NetworkX 그래프 적재
url = "https://snap.stanford.edu/data/higgs-retweet_network.edgelist.gz"
file_path = "higgs-retweet_network.edgelist.gz"
print("데이터 로딩 중...")
urllib.request.urlretrieve(url, file_path)

G = nx.DiGraph()
with gzip.open(file_path, 'rt') as f:
    for line in f:
        src, dst, weight = line.strip().split()
        G.add_edge(int(src), int(dst))

# 노드 ID를 0부터 연속 매핑 (전체 그래프 사용)
mapping = {node: i for i, node in enumerate(G.nodes())}
G_sub = nx.relabel_nodes(G, mapping)
N = G_sub.number_of_nodes()
edge_index = torch.tensor(list(G_sub.edges()), dtype=torch.long).t().contiguous()

# [수정] 피처보다 분할을 먼저 → 테스트 엣지 정보가 피처에 섞이는 누수 방지
data = Data(edge_index=edge_index, num_nodes=N)

# 2. 데이터 분할 ※ 무작위 분할 = '링크 예측' (미래 예측 아님)
# [수정] 학습용 음성은 붙이지 않음 → recon_loss가 매 epoch 직접 샘플링
transform = T.RandomLinkSplit(num_val=0.1, num_test=0.2, is_undirected=False,
                              add_negative_train_samples=False,
                              disjoint_train_ratio=0.3)  # [추가] 학습 정답 엣지 30%를 입력 그래프에서 분리
train_data, val_data, test_data = transform(data)

# 3. [수정] 각 split의 관측 엣지로만 In/Out-degree 피처 계산
def degree_features(ei):
    din, dout = degree(ei[1], N), degree(ei[0], N)
    return torch.stack([torch.log1p(din), torch.log1p(dout)], dim=1)

x_train = degree_features(train_data.edge_index)
mu, sd = x_train.mean(dim=0), x_train.std(dim=0) + 1e-8   # 학습 데이터 기준 표준화
for d in (train_data, val_data, test_data):
    d.x = (degree_features(d.edge_index) - mu) / sd
    d.edge_index = to_undirected(d.edge_index, num_nodes=N)  # [수정] 메시지 양방향 전달

# 4. GCN Encoder + GAE
class GCNEncoder(torch.nn.Module):
    def __init__(self, in_channels, hidden_channels, out_channels):
        super().__init__()
        self.conv1 = GCNConv(in_channels, hidden_channels)
        self.conv2 = GCNConv(hidden_channels, out_channels)

    def forward(self, x, edge_index):
        x = self.conv1(x, edge_index).relu()
        return self.conv2(x, edge_index)

model = GAE(GCNEncoder(in_channels=2, hidden_channels=32, out_channels=16))
optimizer = torch.optim.Adam(model.parameters(), lr=0.01)

# 5. 학습
def train():
    model.train()
    optimizer.zero_grad()
    z = model.encode(train_data.x, train_data.edge_index)
    # [수정] recon_loss의 두 번째 인자는 전부 '양성'으로 취급됨 → 양성 엣지만 전달
    pos_edge_index = train_data.edge_label_index[:, train_data.edge_label == 1]
    loss = model.recon_loss(z, pos_edge_index)
    loss.backward()
    optimizer.step()
    return loss.item()

@torch.no_grad()
def predict(d):
    model.eval()
    z = model.encode(d.x, d.edge_index)
    # [수정] decode()가 이미 sigmoid 적용 → 한 번만
    return model.decode(z, d.edge_label_index).view(-1).cpu().numpy(), d.edge_label.cpu().numpy()

print("모델 학습 시작...")
best_auc, best_epoch, best_state = -1, 0, None  # [수정] 최적 시점 저장
for epoch in range(1, 201):
    loss = train()
    if epoch % 10 == 0:
        p, y = predict(val_data)
        fpr_v, tpr_v, _ = roc_curve(y, p)
        val_auc, val_ap = auc(fpr_v, tpr_v), average_precision_score(y, p)
        print(f'Epoch: {epoch:03d}, Loss: {loss:.4f}, Val AUC: {val_auc:.4f}, Val AP: {val_ap:.4f}')
        if val_auc > best_auc:
            best_auc, best_epoch, best_state = val_auc, epoch, copy.deepcopy(model.state_dict())

model.load_state_dict(best_state)
print(f"최적 epoch: {best_epoch} (Val AUC {best_auc:.4f})")

# 6. 최종 평가
y_val_prob, y_val = predict(val_data)
y_pred_prob, y_true = predict(test_data)

fpr, tpr, _ = roc_curve(y_true, y_pred_prob)
roc_auc = auc(fpr, tpr)
ap_score = average_precision_score(y_true, y_pred_prob)

# [수정] F1 임계값은 검증셋에서 선택 → 테스트셋에 적용
precisions, recalls, thresholds = precision_recall_curve(y_val, y_val_prob)
f1_scores = 2 * precisions * recalls / (precisions + recalls + 1e-10)
best_threshold = thresholds[np.argmax(f1_scores[:-1])]
best_f1 = f1_score(y_true, (y_pred_prob >= best_threshold).astype(int))

print("=" * 50)
print(f"1. ROC AUC: {roc_auc:.4f}")
print(f"2. AP (Average Precision): {ap_score:.4f}")
print(f"3. F1 Score (threshold={best_threshold:.3f}, 검증셋에서 선택): {best_f1:.4f}")
print("=" * 50)

